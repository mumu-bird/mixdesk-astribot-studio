import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {taggedWav} from '../tests/fixtures/audio.js';
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required']});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1080}}),errors=[],remote=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith('http://127.0.0.1:4173'))remote.push(r.url());});
 await page.goto('http://127.0.0.1:4173/');
 await page.locator('#sampler-status').filter({hasText:'已就绪'}).waitFor();
 await page.locator('#sample-file').setInputFiles({name:'Production tone.wav',mimeType:'audio/wav',buffer:taggedWav({duration:3})});
 await page.locator('[data-sample="0"] strong').filter({hasText:'Production tone'}).waitFor();
 await page.getByRole('button',{name:'编辑采样 1',exact:true}).click();
 await page.locator('#sample-name').fill('Production loop');
 await page.locator('#sample-start').fill('.25');
 await page.locator('#sample-end').fill('1.25');
 await page.locator('#sample-gain').fill('80');
 await page.locator('#sample-save').click();
 await page.locator('[data-sample="0"] strong').filter({hasText:'Production loop'}).waitFor();
 await page.locator('[data-sample="0"] .sample-mode').selectOption('loop');
 await page.locator('#sampler-quantize').check();
 await page.locator('#sampler-target').selectOption('0');
 await page.locator('#sampler-beats').selectOption('1');
 await page.getByRole('button',{name:'播放采样 1',exact:true}).click();
 await page.waitForTimeout(150);
 await page.locator('[data-sample=\"0\"] .sample-trigger').filter({hasText:'正在播放'}).waitFor();
 const state={name:await page.locator('[data-sample=\"0\"] strong').textContent(),mode:await page.locator('[data-sample=\"0\"] .sample-mode').inputValue(),source:true};
 await page.getByRole('button',{name:'停止采样 1',exact:true}).click();
 await page.reload();await page.locator('#sampler-status').filter({hasText:'已就绪'}).waitFor();
 assert.equal(await page.locator('[data-sample="0"] strong').textContent(),'Production loop');
 assert.equal(await page.locator('[data-sample="0"] .sample-mode').inputValue(),'loop');
 await page.locator('.sampler-panel').screenshot({path:'screenshots/mixdesk-sampler-v0.8.png'});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.getByRole('button',{name:'编辑采样 1',exact:true}).click();
 assert.ok(await page.locator('#sample-dialog').evaluate(d=>d.scrollWidth<=d.clientWidth));
 await page.screenshot({path:'screenshots/mixdesk-sampler-mobile-v0.8.png',fullPage:true});
 assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
 console.log(JSON.stringify({production:true,restored:true,mode:state.mode,mobileOverflow:false,errors,remoteRequests:remote}));
} finally {await browser.close();}
